package lesson1;

public class PrimitiveVar {
	public static void main(String[] args) {
		int a = 25;
		double b = 19.99d;
		char c = 'A';
		boolean d = true;
		  
	        System.out.println("Count: " + a); 
	        System.out.println("Product Price: " + b);
	        System.out.println("Symbol:" + c);
	        System.out.println("Boolean:" + d);
	}
}
